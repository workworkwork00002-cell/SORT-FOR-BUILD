export function detectLang() {
  const nav = (typeof navigator !== "undefined" && navigator.language) || "en";
  const code = nav.slice(0, 2).toLowerCase();
  return I18N[code] ? code : "en";
}

/* Собирает словарь языка поверх английского: если перевод какого-то
   ключа отсутствует, подставится английский вариант, а не пустота. */
export function makeT(lang) {
  const base = I18N.en;
  const cur = I18N[lang] || {};
  return {
    ...base,
    ...cur,
    views: { ...base.views, ...(cur.views || {}) },
    worlds: { ...base.worlds, ...(cur.worlds || {}) },
    stages: { ...base.stages, ...(cur.stages || {}) },
  };
}

